def calcular_composto(_=None):
    with saida_3d:
        clear_output(wait=True)
    with saida:
        clear_output(wait=True)
        entrada = smiles_box.value.strip()
        if not entrada:
            print('Digite ou cole um SMILES.')
            return
        try:
            mol, multiplos = interpretar_smiles(entrada, fragmento_checkbox.value)
            p = calcular_descritores(mol)  # Não depende do PubChem.
            regras, violacoes = avaliar_lipinski(p)
        except Exception as erro:
            print('Não foi possível interpretar ou calcular a estrutura:', erro)
            return

        calcular_btn.disabled = True
        calcular_btn.description = 'CALCULANDO...'
        try:
            info = consultar_pubchem(mol)
            nome = info['nome'] if info else 'Composto não identificado no PubChem'
            cid = info['cid'] if info else None
            formula = rdMolDescriptors.CalcMolFormula(mol)
            passou = violacoes <= 1
            resultado = 'PASSA' if passou else 'NÃO PASSA'
            cor = '#287b43' if passou else '#c33'
            display(HTML(f'<h3>{html.escape(nome)}</h3><p>Fórmula molecular: {html.escape(formula)} | '
                         f'PubChem CID: {cid if cid is not None else "não disponível"}</p>'))
            if multiplos:
                aviso = ('apenas o maior fragmento foi utilizado' if fragmento_checkbox.value
                         else 'a estrutura completa, incluindo todos os fragmentos, foi utilizada')
                print('ATENÇÃO: SMILES com múltiplos fragmentos;', aviso + '.')
            display(HTML(tabela_html('Regra dos 5 de Lipinski', regras)))
            display(HTML(f'<p><b>Violações:</b> {violacoes} | '
                         f'<b style="color:{cor}">{resultado}</b> (critério: até uma violação)</p>'))
            display(HTML('<p><i>Triagem computacional: os critérios não comprovam absorção, eficácia ou segurança.</i></p>'))
            display(HTML('<h4>Estrutura 2D</h4>'))
            display(Draw.MolToImage(mol, size=(420, 300)))
            historico.append({
                'data_utc': datetime.now(timezone.utc).isoformat(),
                'smiles_inserido': entrada,
                'smiles_analisado': Chem.MolToSmiles(mol, canonical=True),
                'maior_fragmento': bool(multiplos and fragmento_checkbox.value),
                'nome': nome,
                'cid': cid,
                'formula': formula,
                'massa_Da': round(p['massa'], 4),
                'logP_RDKIT': round(p['logp'], 4),
                'HBD': p['hbd'],
                'HBA': p['hba'],
                'violacoes_lipinski': violacoes,
                'classificacao_lipinski': resultado,
                'rdkit_versao': rdBase.rdkitVersion,
            })
            print(f'Registro salvo no histórico desta sessão: {len(historico)} análise(s).')
            # Renderiza fora do contexto 'with saida' abaixo.
        except Exception as erro:
            print('Ocorreu um erro durante a apresentação:', str(erro))
        finally:
            calcular_btn.disabled = False
            calcular_btn.description = 'CALCULAR'
    if 'mol' in locals() and 'cid' in locals():
        mostrar_3d(mol, cid)


