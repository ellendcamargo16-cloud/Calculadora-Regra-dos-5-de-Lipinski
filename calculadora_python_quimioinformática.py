def criar_sessao():
    sessao = requests.Session()
    tentativas = Retry(
        total=2,
        backoff_factor=0.5,
        status_forcelist=(429, 500, 502, 503, 504),
        allowed_methods=frozenset(['GET']),
    )
    sessao.mount('https://', HTTPAdapter(max_retries=tentativas))
    return sessao

SESSAO = criar_sessao()

def interpretar_smiles(smiles, usar_maior_fragmento=False):
    mol_original = Chem.MolFromSmiles(smiles)
    if mol_original is None:
        raise ValueError('SMILES inválido. Verifique a estrutura informada.')
    fragmentos = Chem.GetMolFrags(mol_original, asMols=True)
    multiplos = len(fragmentos) > 1
    if multiplos and usar_maior_fragmento:
        mol = max(fragmentos, key=lambda m: (m.GetNumHeavyAtoms(), Descriptors.MolWt(m)))
    else:
        mol = mol_original
    return mol, multiplos

def calcular_descritores(mol):
    return {
        'massa': Descriptors.MolWt(mol),
        'logp': Crippen.MolLogP(mol),
        'hbd': Lipinski.NumHDonors(mol),
        'hba': Lipinski.NumHAcceptors(mol),
    }

def avaliar_lipinski(p):
    regras = [
        ('Massa molecular ≤ 500 Da', f"{p['massa']:.2f} Da", p['massa'] <= 500),
        ('LogP ≤ 5', f"{p['logp']:.2f}", p['logp'] <= 5),
        ('Doadores de H (HBD) ≤ 5', str(p['hbd']), p['hbd'] <= 5),
        ('Aceptores de H (HBA) ≤ 10', str(p['hba']), p['hba'] <= 10),
    ]
    return regras, sum(not ok for _, _, ok in regras)

def consultar_pubchem(mol):
    """Busca metadados opcionais; falhas não impedem os cálculos."""
    smiles = Chem.MolToSmiles(mol, canonical=True)
    try:
        r = SESSAO.post(
            f'{PUBCHEM}/compound/fastidentity/smiles/cids/JSON',
            data={'smiles': smiles}, timeout=TIMEOUT,
        )
        if not r.ok:
            return None
        cids = r.json().get('IdentifierList', {}).get('CID', [])
        if not cids:
            return None
        cid = cids[0]
    except (requests.RequestException, ValueError, TypeError, KeyError, IndexError):
        return None
    nome = 'Nome não disponível'
    formula = rdMolDescriptors.CalcMolFormula(mol)
    try:
        r = SESSAO.get(
            f'{PUBCHEM}/compound/cid/{cid}/property/Title,MolecularFormula/JSON',
            timeout=TIMEOUT,
        )
        if r.ok:
            propriedades = r.json().get('PropertyTable', {}).get('Properties', [])
            if propriedades:
                nome = propriedades[0].get('Title', nome)
                formula = propriedades[0].get('MolecularFormula', formula)
    except (requests.RequestException, ValueError, TypeError, KeyError, IndexError):
        pass
    return {'cid': cid, 'nome': nome, 'formula': formula}

def gerar_3d_rdkit(mol):
    """Gera uma conformação estimada, não uma estrutura experimental."""
    try:
        mol_h = Chem.AddHs(Chem.Mol(mol))
        parametros = AllChem.ETKDGv3()
        parametros.randomSeed = 42
        if AllChem.EmbedMolecule(mol_h, parametros) != 0:
            return None
        if AllChem.MMFFHasAllMoleculeParams(mol_h):
            AllChem.MMFFOptimizeMolecule(mol_h, maxIters=500)
        elif AllChem.UFFHasAllMoleculeParams(mol_h):
            AllChem.UFFOptimizeMolecule(mol_h, maxIters=500)
        return Chem.MolToMolBlock(mol_h)
    except Exception:
        return None

def obter_estrutura_3d(cid, mol):
    if cid is not None:
        try:
            r = SESSAO.get(f'{PUBCHEM}/compound/cid/{cid}/SDF?record_type=3d', timeout=TIMEOUT)
            if r.ok and r.text.strip():
                return r.text, 'PubChem'
        except requests.RequestException:
            pass
    sdf = gerar_3d_rdkit(mol)
    return (sdf, 'RDKit (conformação estimada)') if sdf else (None, None)

def tabela_html(titulo, linhas):
    corpo = ''.join(
        f'<tr><td style="padding:5px 15px 5px 0">{html.escape(desc)}</td>'
        f'<td style="padding:5px 15px 5px 0">{html.escape(valor)}</td>'
        f'<td style="color:{"#287b43" if ok else "#c33"}">{"✓" if ok else "✗"}</td></tr>'
        for desc, valor, ok in linhas
    )
    return f'<h4>{html.escape(titulo)}</h4><table>{corpo}</table>'

def mostrar_3d(mol, cid):
    """Renderiza 3D fora da área Output dos widgets (mais estável no Colab)."""
    with saida_3d:
        clear_output(wait=True)
        display(HTML('<h4>Estrutura tridimensional</h4>'))
        sdf, origem = obter_estrutura_3d(cid, mol)
        if not sdf:
            print('Não foi possível obter ou gerar uma estrutura 3D.')
            return
        # Confirma que o SDF realmente contém uma estrutura 3D válida.
        mol_3d = Chem.MolFromMolBlock(sdf, sanitize=True, removeHs=False)
        if mol_3d is None or mol_3d.GetNumConformers() == 0 or not mol_3d.GetConformer().Is3D():
            sdf = gerar_3d_rdkit(mol)
            origem = 'RDKit (conformação estimada; SDF do PubChem inválido)' if sdf else None
        if not sdf:
            print('Não foi possível interpretar ou gerar o modelo tridimensional.')
            return
        print('Origem:', origem)
        if origem.startswith('RDKit'):
            print('Modelo computacional estimado; não representa necessariamente a conformação bioativa.')
        try:
            viewer = py3Dmol.view(width=700, height=450)
            viewer.addModel(sdf, 'sdf')
            viewer.setStyle({'stick': {'radius': 0.16}, 'sphere': {'scale': 0.26}})
            viewer.setBackgroundColor('white')
            viewer.zoomTo()
            # Renderização explícita em HTML, em uma área separada da saída de resultados.
            # Evita que clear_output() apague o JavaScript do visualizador.
            display(HTML(viewer._make_html()))
        except Exception as erro:
            print('Não foi possível exibir o modelo 3D:', erro)
            print('Experimente executar novamente a célula no Google Colab.')

