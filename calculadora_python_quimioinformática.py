def verificar_calculos(_=None):
    """Teste de consistência de funções RDKit; não substitui validação científica externa."""
    referencias = [
        # Massa teórica aproximada e contagens de doadores/aceptores, para teste de regressão.
        ('Aspirina', EXEMPLOS['Aspirina'], 180.159, 1, 3),
        ('Cafeína', EXEMPLOS['Cafeína'], 194.194, 0, 6),
        ('Paracetamol', EXEMPLOS['Paracetamol'], 151.165, 2, 2),
    ]
    with saida:
        clear_output()
        print('VERIFICAÇÃO DE CONSISTÊNCIA DOS CÁLCULOS (RDKit)')
        print('Versão RDKit:', rdBase.rdkitVersion)
        print('Valores de referência: massa teórica aproximada e contagens esperadas.')
        aprovados = 0
        for nome, smiles, massa_ref, hbd_ref, hba_ref in referencias:
            mol = Chem.MolFromSmiles(smiles)
            if mol is None:
                print(f'{nome}: FALHA (SMILES inválido)')
                continue
            p = calcular_descritores(mol)
            ok = (abs(p['massa'] - massa_ref) < 0.03 and p['hbd'] == hbd_ref and p['hba'] == hba_ref)
            aprovados += bool(ok)
            print(f'{nome}: {"OK" if ok else "VERIFICAR"} | Massa {p["massa"]:.3f} Da | HBD {p["hbd"]} | HBA {p["hba"]}')
        print(f'Conferências aprovadas: {aprovados}/{len(referencias)}')
        print('Esta checagem não valida LogP nem substitui comparação com fontes independentes.')

